BY_KEY = {s.key: s for s in SCHEMES}

# Какие признаки на какую схему указывают. Порядок важен: более специфичные
# схемы идут первыми, общие — последними.
# Правило срабатывает, только если есть ВСЕ перечисленные признаки: иначе
# просьба денег в любом тексте опознавалась бы как «мама, это я».
_RULES: list[tuple[str, set[str], tuple[str, ...]]] = [
    ("charity",    {"money_request"}, ("ребенок", "ребёнок", "смесь", "помогите", "займите")),
    ("relative",   {"new_contact"}, ()),
    # Просьба денег со срочностью в обращении к родным — та же схема,
    # даже если про новый номер прямо не сказано.
    ("relative",   {"money_request", "urgency"},
     ("мам", "пап", "сын", "доч", "брат", "сестр", "бабул", "дедул")),
    ("bank",       {"code_request"}, ("банк", "безопасност", "карт")),
    ("house_chat", set(), ("домовой чат", "чат жильцов", "перерасчёт", "жкх", "соседи")),
    ("prize",      {"too_good"}, ("выигр", "приз", "розыгрыш", "поздравляем")),
    ("job",        {"too_good"}, ("работ", "заработок", "подработк", "ваканс", "доход")),
    ("obfuscation", {"obfuscation"}, ()),
    ("link",       {"external_link"}, ()),
    ("job",        set(), ("работ", "заработок", "подработк", "ваканс")),
]


def identify(markers: list[dict] | None, text: str) -> Scheme | None:
    """Какая это схема. None, если не узнаём — и тогда так и говорим."""
    kinds = {m.get("type") for m in (markers or []) if isinstance(m, dict)}
    low = text.casefold()
    for key, need_kinds, need_words in _RULES:
        if need_kinds and not need_kinds <= kinds:
            continue
        if need_words and not any(w in low for w in need_words):
            continue
        if not need_kinds and not need_words:
            continue
        return BY_KEY[key]
    return None
